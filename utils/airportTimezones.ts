/**
 * Compute the actual block time in minutes between two airport-local HH:MM
 * times, correctly accounting for timezone differences.
 *
 * @param depTime  "HH:MM" in departure airport local time
 * @param arrTime  "HH:MM" in arrival airport local time
 * @param depIata  Departure airport IATA code
 * @param arrIata  Arrival airport IATA code
 * @param date     Flight date in "YYYY-MM-DD" (used to resolve DST offsets)
 * @returns        Duration in minutes, or null if timezones are unknown
 */
export function computeActualBlockMinutes(
  depTime: string,
  arrTime: string,
  depIata: string,
  arrIata: string,
  date: string,
): number | null {
  const depTz = AIRPORT_TIMEZONES[depIata];
  const arrTz = AIRPORT_TIMEZONES[arrIata];
  if (!depTz || !arrTz) return null;

  // Parse HH:MM
  const [dh, dm] = depTime.split(":").map(Number);
  const [ah, am] = arrTime.split(":").map(Number);
  if ([dh, dm, ah, am].some(isNaN)) return null;

  // Build ISO-like strings that Intl can resolve to UTC via the given timezone.
  // We use a trick: format a known UTC epoch in each timezone to find the
  // UTC offset for that date, then apply it to convert local → UTC.
  const getOffsetMinutes = (tz: string, hours: number, minutes: number): number => {
    // Create a date in that timezone for the flight date at the given local time
    const isoLocal = `${date}T${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:00`;
    // Use Intl.DateTimeFormat to determine UTC offset by formatting a UTC date
    // in the target timezone and comparing
    const probe = new Date(`${isoLocal}Z`); // treat as UTC first
    const formatter = new Intl.DateTimeFormat("en-US", {
      timeZone: tz,
      hour: "2-digit",
      minute: "2-digit",
      hour12: false,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
    });
    const parts = formatter.formatToParts(probe);
    const p: Record<string, number> = {};
    for (const { type, value } of parts) {
      if (["year", "month", "day", "hour", "minute"].includes(type))
        p[type] = parseInt(value, 10);
    }
    // Local time in this tz when UTC clock shows isoLocal
    const localTotal = p["hour"] * 60 + p["minute"];
    const utcTotal   = hours * 60 + minutes;
    // offset = utc - local  →  local + offset = utc
    return utcTotal - localTotal;
  };

  const depOffsetMin = getOffsetMinutes(depTz, dh, dm);
  const arrOffsetMin = getOffsetMinutes(arrTz, ah, am);

  const depUtcMin = dh * 60 + dm + depOffsetMin;
  const arrUtcMin = ah * 60 + am + arrOffsetMin;

  let diff = arrUtcMin - depUtcMin;
  // Handle overnight flights (diff could be negative if arrival is next day)
  if (diff < 0) diff += 24 * 60;
  // Cap at 24h — anything longer is almost certainly a next-day wraparound edge case
  if (diff > 24 * 60) diff -= 24 * 60;

  return diff;
}
